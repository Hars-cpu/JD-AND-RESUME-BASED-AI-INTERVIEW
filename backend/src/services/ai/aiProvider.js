/**
 * @file aiProvider.js
 * @summary Unified AI provider that wraps the Groq SDK (gpt oss 120B model) for use
 *          across all interview services. Handles system prompts, multi-turn chat history,
 *          optional JSON-mode output, and automatic retry-with-backoff for rate-limit (429)
 *          and server-error (5xx) responses.
 *
 * @functions
 * - generateContent: Builds a Groq chat completion request from the prompt, optional system instruction,
 *                    and optional history, retries up to 3 times with exponential backoff on rate-limit
 *                    or server errors, and returns the raw text content of the first choice.
 */

const Groq = require('groq-sdk');

const DEFAULT_MODEL = 'openai/gpt-oss-120b';

/**
 * Generates content using the Groq API.
 * @param {Object} options
 * @param {string} options.prompt - The user prompt.
 * @param {string} [options.systemInstruction] - Optional system prompt.
 * @param {Array} [options.history] - Optional chat history [{ role: 'user'|'model', parts: [{ text: '...' }] }].
 * @param {boolean} [options.jsonMode=false] - Whether to enforce JSON object output.
 * @returns {Promise<string>}
 */
const generateContent = async ({ prompt, systemInstruction = '', history = [], jsonMode = false }) => {
  if (!process.env.GROQ_API_KEY) {
    throw new Error('GROQ_API_KEY not configured');
  }

  const groq = new Groq({
    apiKey: process.env.GROQ_API_KEY,
  });

  const messages = [];

  if (systemInstruction) {
    messages.push({ role: 'system', content: systemInstruction });
  }

  if (history && history.length > 0) {
    history.forEach((msg) => {
      // Map Gemini format to Groq format
      const role = msg.role === 'model' ? 'assistant' : 'user';
      let content = '';

      if (msg.parts && msg.parts.length > 0) {
        content = msg.parts[0].text;
      } else if (msg.message) {
        content = msg.message;
      } else if (msg.text) {
        content = msg.text;
      }

      if (content) {
        messages.push({ role, content });
      }
    });
  }

  if (prompt) {
    messages.push({ role: 'user', content: prompt });
  }

  const completionOptions = {
    messages,
    model: DEFAULT_MODEL,
    temperature: 0.7,
  };

  if (jsonMode) {
    completionOptions.response_format = { type: 'json_object' };
  }

  const MAX_RETRIES = 3;
  let attempt = 0;

  while (attempt < MAX_RETRIES) {
    try {
      const chatCompletion = await groq.chat.completions.create(completionOptions);
      let rawContent = chatCompletion.choices[0]?.message?.content || '';
      // Strip <think>...</think> blocks generated by reasoning models
      return rawContent.replace(/<think>[\s\S]*?<\/think>\s*/gi, '').trim();
    } catch (error) {
      attempt++;
      const isRateLimitOrServerError = error.status === 429 || error.status >= 500;
      
      if (!isRateLimitOrServerError || attempt >= MAX_RETRIES) {
        throw error;
      }
      
      console.warn(`[aiProvider] Groq API error (${error.status}). Retrying attempt ${attempt} of ${MAX_RETRIES}...`);
      await new Promise(resolve => setTimeout(resolve, 1000 * Math.pow(2, attempt)));
    }
  }
};

module.exports = {
  generateContent,
  DEFAULT_MODEL,
};
