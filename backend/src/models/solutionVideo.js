/**
 * @file solutionVideo.js
 * @summary Mongoose schema for the SolutionVideo collection.
 *          Each document links a Cloudinary-hosted video to a specific Problem and the admin User
 *          who uploaded it, storing the CDN public ID, secure streaming URL, thumbnail, and duration.
 *
 * @schema fields
 * - problemId: ObjectId ref to the Problem this video explains
 * - userId: ObjectId ref to the admin User who uploaded the video
 * - cloudinaryPublicId: unique asset ID used to manage/delete the file on Cloudinary
 * - secureUrl: HTTPS streaming URL served to the frontend video player
 * - thumbnailUrl: preview image URL generated by Cloudinary
 * - duration: video length in seconds
 * - timestamps: auto-managed createdAt / updatedAt
 */

const mongoose = require('mongoose');
const {Schema} = mongoose;

const videoSchema = new Schema({
    problemId: {
        type: Schema.Types.ObjectId,
        ref: 'problem',
        required: true
    },
    userId: {
    type: Schema.Types.ObjectId,
    ref: 'user',
    required: true,
   },
   cloudinaryPublicId: {
    type: String,
    required: true,
    unique: true
  },
  secureUrl: {
    type: String,
    required: true
  },
  thumbnailUrl: {
    type: String
  },
  duration: {
    type: Number,
    required: true
  },
},{
    timestamps:true
});



const SolutionVideo = mongoose.model("solutionVideo",videoSchema);

module.exports = SolutionVideo;
